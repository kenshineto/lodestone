package cat.freya.lodestone.internal

import org.gradle.api.Project
import org.gradle.kotlin.dsl.configure
import org.jetbrains.kotlin.gradle.dsl.KotlinJvmProjectExtension

internal fun Project.configureBuildInfo(buildInfo: Map<String, Any>) {
    val output = layout.buildDirectory.dir("generated/sources/buildInfo/kotlin")
    val packageName = group.toString()

    val task =
        tasks.register("generateBuildInfo") {
            outputs.dir(output)
            doLast {
                val packageDir = output.get().asFile.resolve(packageName.replace('.', '/'))
                packageDir.mkdirs()
                packageDir
                    .resolve("BuildInfo.kt")
                    .writeText(
                        buildString {
                            appendLine("package $packageName")
                            appendLine("/** Generated by Gradle. DO NOT EDIT. */")
                            appendLine("object BuildInfo {")
                            buildInfo.forEach { (key, value) ->
                                appendLine("    const val ${key} = ${value.toKotlinLiteral()}")
                            }
                            appendLine("}")
                        },
                    )
            }
        }

    extensions.configure<KotlinJvmProjectExtension> {
        sourceSets.named("main") {
            kotlin.srcDir(task)
        }
    }
}

private fun Any?.toKotlinLiteral(): String =
    when (this) {
        null -> "null"
        is String -> "\"${this}\""
        is Number,
        is Boolean -> toString()
        else -> "\"${toString()}\""
    }
