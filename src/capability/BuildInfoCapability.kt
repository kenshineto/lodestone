package cat.freya.lodestone.capability

import org.gradle.api.Project
import org.gradle.api.plugins.JavaPluginExtension
import org.gradle.kotlin.dsl.configure

internal fun Project.configureBuildInfo(buildInfo: Map<String, Any>) {
    val output = layout.buildDirectory.dir("generated/sources/buildInfo/java")
    val packageName = group.toString()

    val task =
        tasks.register("generateBuildInfo") {
            outputs.dir(output)
            doLast {
                val packageDir = output.get().asFile.resolve(packageName.replace('.', '/'))
                packageDir.mkdirs()
                packageDir
                    .resolve("BuildInfo.java")
                    .writeText(
                        buildString {
                            appendLine("package $packageName;")
                            appendLine("/** Generated by Gradle. DO NOT EDIT. */")
                            appendLine("public class BuildInfo {")
                            buildInfo.forEach { (key, value) ->
                                val type = value.javaClass.name
                                appendLine("    public static final $type $key = ${value.toJavaLiteral()};")
                            }
                            appendLine("}")
                        },
                    )
            }
        }

    extensions.configure<JavaPluginExtension> {
        sourceSets.named("main") {
            java.srcDir(task)
        }
    }
}

private fun Any?.toJavaLiteral(): String =
    when (this) {
        null -> "null"
        is String -> "\"${this}\""
        is Number,
        is Boolean -> toString()
        else -> "\"${toString()}\""
    }
